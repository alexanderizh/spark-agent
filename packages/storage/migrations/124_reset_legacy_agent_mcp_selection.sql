-- 124_reset_legacy_agent_mcp_selection.sql
-- 修复 0.14.14「Agent 级 MCP 按需挂载」激活休眠字段引发的升级回归。
--
-- 背景：agents.mcp_server_ids_json 在 53f2a02cf（2026-07-16，MCP 全局化：前端
-- 配置收口，不再写入该字段）到 c3b7d78ed（2026-10-09，按需挂载：重新启用该
-- 字段）之间处于休眠状态——前端不写入、后端不读取，期间残留的值不表达任何
-- 用户意图（典型形态是旧版选择器随保存写入的「仅含 playwright」等托管 server
-- 清单）。0.14.14 重新激活该字段并采用「非空 = 白名单，仅挂载所选」语义后，
-- 这些存量值把 Agent 从「全部 MCP 可用」锁成「只挂个别 MCP」：可选档内置 MCP
-- （平台管理 / 插件工具 / 子应用 / 多媒体生成 / 图片生成 / 浏览器自动化 /
-- 桌面控制 / 联网搜索）被整体摘除，用户必须逐个手动勾选才能恢复。
--
-- 处理：把所有非空选择重置为 []（= 全部可用），还原升级前行为。依据是该字段
-- 休眠期内的任何值都不代表真实意图；0.14.14 之后新写入的选择同样无法与「被
-- 误导 UI 诱导的误解操作」区分，一并重置以保证受影响用户回到可用状态。用户
-- 可在 Agent 编辑页重新配置白名单。
--
-- 幂等：唯一保留的形态是规范的 '[]'，重复执行无副作用；空白串与畸形 JSON
-- 一并规范化为 '[]'，避免下游解析出未定义行为。

UPDATE agents
SET mcp_server_ids_json = '[]',
    updated_at = datetime('now')
WHERE mcp_server_ids_json IS NOT NULL
  AND trim(mcp_server_ids_json) <> '[]';
